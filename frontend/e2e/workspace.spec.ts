import { test, expect } from '@playwright/test';

test('real corpus workflow: evidence, feedback, repeat, collection, export, persistence, settings', async ({ page }, testInfo) => {
  await page.goto('/');
  await page.getByLabel('Start with a synthetic example').selectOption('secured_driver_backpack');
  await page.getByRole('button', { name: 'Create matter →' }).click();
  await expect(page.getByRole('heading', { name: 'Arrested driver and a backpack in the car' })).toBeVisible();
  await page.getByRole('button', { name: 'Search collection →' }).click();
  const cards=page.locator('.case-card');
  await expect(cards).toHaveCount(3);
  await cards.first().getByRole('button', { name: 'Inspect evidence' }).click();
  await expect(page.locator('dialog blockquote').first()).toContainText(/\w{8}/);
  await expect(page.getByRole('link', { name: 'Open official opinion' })).toHaveAttribute('href', /govinfo.gov|tile.loc.gov/);
  await page.getByRole('button', { name: 'Close source inspection' }).click();
  await cards.first().getByRole('button', { name: 'Save case' }).click();
  await expect(page.locator('.saved-list li')).toHaveCount(1);
  await cards.first().getByRole('button', { name: 'Relevant', exact: true }).click();
  await cards.first().getByLabel('Optional feedback reason').fill('secured driver arrest offense');
  await cards.first().getByRole('button', { name: 'Save reason' }).click();
  await expect(cards.first().getByRole('button', { name: 'Save reason' })).toBeDisabled();
  await page.getByRole('button', { name: 'Search again →' }).click();
  await expect(page.getByLabel('Search round')).toContainText('Round 2');
  await page.locator('.trace summary').click();
  await expect(page.locator('.trace')).toContainText('secured driver arrest offense');
  const downloadPromise=page.waitForEvent('download');
  await page.getByRole('link', { name: /Export collection/ }).click();
  const download=await downloadPromise;
  await download.saveAs(testInfo.outputPath('selected-cases.csv'));
  expect(download.suggestedFilename()).toBe('selected-cases.csv');
  await page.reload();
  await expect(page.locator('.saved-list li')).toHaveCount(1);
  await expect(page.getByLabel('Search round')).toContainText('Round 2');
  await page.getByRole('button', { name: /Workspace settings/ }).click();
  await page.getByLabel('Appearance').selectOption('dark');
  await expect(page.locator('html')).toHaveAttribute('data-theme','dark');
  await page.reload();
  await expect(page.locator('html')).toHaveAttribute('data-theme','dark');
  await page.getByRole('button', { name: /Workspace settings/ }).click();
  await page.getByLabel('Appearance').selectOption('light');
  await page.getByRole('button', { name: 'Close', exact:true }).click();
  await page.screenshot({path:testInfo.outputPath('workspace-desktop.png'),fullPage:true});
  await page.setViewportSize({width:390,height:844});
  await expect(page.getByRole('button', { name: 'Search again →' })).toBeVisible();
  expect(await page.evaluate(()=>document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy();
  await page.screenshot({path:testInfo.outputPath('workspace-mobile.png'),fullPage:true});
});
